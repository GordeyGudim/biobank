"""Ошибки, которые видит пользователь (текст — для человека).

Отдельный модуль, чтобы ими пользовались все слои (правки, пользователи, права, журнал
изменений) без циклических импортов. Для совместимости EditError и NotFoundError
по-прежнему можно импортировать из biobank.edit.
"""


class EditError(Exception):
    """Правку нельзя выполнить; текст ошибки — для пользователя."""


class NotFoundError(EditError):
    """Нет такой записи (особи, проблемы, базы) — в вебе это страница 404."""


class PermissionDenied(EditError):
    """Нет прав на действие (роль не та, чужая запись, вход закрыт) — в вебе это 403."""
